use crate::session::Action;

pub fn label(action: &Action) -> String {
    match *action {
        Action::Key(usage) => key_name(usage).unwrap_or_else(|| format!("key {usage:02X}")),
        Action::BrightnessDown => "brightness down".to_string(),
        Action::BrightnessUp => "brightness up".to_string(),
        Action::MissionControl => "mission control".to_string(),
        Action::Dashboard => "dashboard".to_string(),
        Action::Search => "search".to_string(),
        Action::MicrophoneMute => "microphone mute".to_string(),
        Action::NumLock => "num lock".to_string(),
        Action::Sleep => "sleep".to_string(),
        Action::TrackPrevious => "previous track".to_string(),
        Action::PlayPause => "play/pause".to_string(),
        Action::TrackNext => "next track".to_string(),
        Action::Mute => "mute".to_string(),
        Action::VolumeDown => "volume down".to_string(),
        Action::VolumeUp => "volume up".to_string(),
        Action::Function => "fn".to_string(),
        Action::Eject => "eject".to_string(),
    }
}

pub fn consumer_name(usage: u16) -> String {
    let name = match usage {
        0x0000 => return "consumer up".to_string(),
        0x006F => "brightness up",
        0x0070 => "brightness down",
        0x00B5 => "next track",
        0x00B6 => "previous track",
        0x00B8 => "eject",
        0x00CD => "play/pause",
        0x00E2 => "mute",
        0x00E9 => "volume up",
        0x00EA => "volume down",
        0x0221 => "search",
        _ => return format!("consumer {usage:04X}"),
    };
    name.to_string()
}

fn key_name(usage: u16) -> Option<String> {
    let name = match usage {
        0x04..=0x1D => return Some(((b'A' + (usage as u8 - 0x04)) as char).to_string()),
        0x1E => "1",
        0x1F => "2",
        0x20 => "3",
        0x21 => "4",
        0x22 => "5",
        0x23 => "6",
        0x24 => "7",
        0x25 => "8",
        0x26 => "9",
        0x27 => "0",
        0x28 => "enter",
        0x29 => "escape",
        0x2A => "backspace",
        0x2B => "tab",
        0x2C => "space",
        0x2D => "-",
        0x2E => "=",
        0x2F => "[",
        0x30 => "]",
        0x31 => "\\",
        0x33 => ";",
        0x34 => "'",
        0x35 => "`",
        0x36 => ",",
        0x37 => ".",
        0x38 => "/",
        0x39 => "caps lock",
        0x3A => "F1",
        0x3B => "F2",
        0x3C => "F3",
        0x3D => "F4",
        0x3E => "F5",
        0x3F => "F6",
        0x40 => "F7",
        0x41 => "F8",
        0x42 => "F9",
        0x43 => "F10",
        0x44 => "F11",
        0x45 => "F12",
        0x49 => "insert",
        0x4A => "home",
        0x4B => "page up",
        0x4C => "delete",
        0x4D => "end",
        0x4E => "page down",
        0x4F => "right",
        0x50 => "left",
        0x51 => "down",
        0x52 => "up",
        0x53 => "num lock",
        0x64 => "non-US \\",
        0xE0 => "left ctrl",
        0xE1 => "left shift",
        0xE2 => "left alt",
        0xE3 => "left cmd",
        0xE4 => "right ctrl",
        0xE5 => "right shift",
        0xE6 => "right alt",
        0xE7 => "right cmd",
        _ => return None,
    };
    Some(name.to_string())
}
